// D 表示击倒；非攻击动作不具有常规命中/防御硬直差。
export function formatFrames(value, advantage = false) {
  if (value === 'D') return '击倒'
  if (value === '-') return '不适用'
  if (value === '*') return '见动作说明'
  if (value == null || value === '' || (typeof value === 'number' && !Number.isFinite(value)))
    return '资料未提供'
  if (/^[+-]?\d+$/.test(String(value)))
    return (advantage && Number(value) > 0 ? '+' : '') + Number(value) + 'F'
  return String(value)
    .replace(' total frames', 'F 全程')
    .replace(/^(\d+)\+(\d+) frame\(s\) after landing$/, '$1F + 落地 $2F')
    .replace(' frame(s) after landing', 'F 落地收招')
}

