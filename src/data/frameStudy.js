function frameSet(characterId, indices, scope) {
  return {
    version: reference.version,
    checkedAt: reference.checkedAt,
    sourceUrl: reference.sourceUrls[characterId],
    comparisonUrl: 'https://ultimateframedata.com/sf6/' + characterId,
    scope,
    variants: indices.map((id, i) => ({
      ...reference.records[characterId][id],
      label:
        indices.length === 3
          ? ['轻', '中', '重'][i]
          : indices.length === 2
            ? ['普通', 'OD'][i]
            : '本条',
    })),
  }
}
export function moveStudy(characterId, number) {
  const normals = number <= 2
  const advice = normals ? normalAdvice[characterId][number - 1] : null
  return {
    moveGroup: normals ? '拳脚 / 目标连段' : '必杀 / 特殊动作',
    frames: frameSet(
      characterId,
      moveRows[characterId][number - 1],
      scopes[characterId][number - 1],
    ),
    hitAdvice: advice?.[0],
    blockAdvice: advice?.[1],
    whiffRisk: advice?.[2],
    actionAdvice: normals ? null : specialNotes[characterId][number - 3],
  }
}

