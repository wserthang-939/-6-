const slugs = { jp: 'JP', aki: 'agui', ryu: 'long', ken: 'ken', jamie: 'jiemi', mai: 'wu' }
const guide = (c) => `https://www.vi-ko.cn/pages/characters/${slugs[c]}.html`
const ufd = (c) => `https://ultimateframedata.com/sf6/${c}`
const readable = (value) =>
  value
    .replaceAll('Knockdown', '击倒')
    .replaceAll('KD', '击倒')
    .replaceAll('Limited Juggle State, ', '可浮空追击；')
    .replaceAll('on hit/block', '命中或被防')
    .replaceAll('on whiff', '挥空时')
    .replaceAll('minimum', '最低')
    .replaceAll('Variable ', '随命中情况变化的')
    .replaceAll('0-3 Drinks', '0–3 酒')
    .replaceAll('4 Drinks', '4 酒')
export function frames(c, name, scope) {
  const r = snapshot.records[c][name]
  if (!r) throw new Error(`缺少帧数：${c}/${name}`)
  return {
    version: snapshot.source,
    checkedAt: snapshot.checkedAt,
    sourceUrl: ufd(c),
    comparisonUrl: guide(c),
    comparisonLabel: '连段资料对照 ↗',
    activeMode: 'duration',
    scope,
    variants: [
      {
        name,
        label: '本条',
        startup: r.startup,
        active: r.activeframes,
        recovery: readable(r.recovery),
        onHit: readable(r.onhit),
        onBlock: r.onblock,
        cancel: r.cancellable || '见招式说明',
      },
    ],
  }
}

