const ufd = (characterId) => `https://ultimateframedata.com/sf6/${characterId}`

function customStudy(characterId, moveName, scope, note) {
  const studyFrames = frames(characterId, moveName, scope)
  studyFrames.enderAdvantage = studyFrames.variants[0].onHit
  studyFrames.enderSourceUrl = ufd(characterId)
  studyFrames.enderSourceNote = `UFD 单招参考；${note}`
  return { frames: studyFrames }
}

function makeCombo({ characterId, number, base, ender, ...content }) {
  const study = base
    ? comboStudy(characterId, base)
    : customStudy(characterId, ender.name, ender.scope, ender.note)
  return {
    ...study,
    id: `${characterId}-combo-${number}`,
    characterId,
    kind: 'combo',
    difficulty: content.difficulty || '进阶',
    sourceUrl: sources[characterId],
    tips: [],
    ...content,
    followUp: comboFollowUp(characterId, number),
  }
}

