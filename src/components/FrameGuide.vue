    <summary>帧数怎么看？<span>发生 · 有利 · 风险</span></summary>
    <dl>
      <dt>发生 / 持续 / 收招</dt>
      <dd>多久打出来、判定持续多久、动作结束前还要多久。发生越快，不等于距离越远或一定安全。</dd>
      <dt>命中有利 / 防御有利</dt>
      <dd>
        双方恢复行动的先后差。+ 表示你先动，− 表示对手先动，0 表示同时恢复。命中与被防必须分开看。
      </dd>
      <dt>有利之后能做什么？</dt>
      <dd>
        再看距离、下一招发生和对手选项。正帧不保证必能投或形成连防；负帧也不一定能被确反，对手还要够快、够远。
      </dd>
      <dt>击倒后还能压吗？</dt>
      <dd>
        看击倒有利和起身方式。前冲、走路或其他动作会用掉时间，不能把收尾优势直接当成贴身后的优势。
      </dd>
      <dt>挥空风险</dt>
      <dd>挥空没有固定的“被防负帧”。要看剩余收招、双方距离，以及对手有没有能打到你的招式。</dd>
    </dl>
    <p>
